// Builds the game's background music from free (CC0) tracks.
//
// Each source is downloaded once into tools/audio/.cache (zips are unpacked). Every track is
// repeated `repeat` times (most sources are short seamless loops), faded out at the very end,
// loudness-normalised with a two-pass EBU R128 loudnorm so all tracks sit at the same level, and
// encoded to MP3 (plays in every browser, Safari included, and streams through an <audio> element).
// How loud the music sits under the sound effects belongs to the game code, not to these files.
//
// Writes <out>/<id>.mp3, <out>/tracks.json (the playlist) and <out>/CREDITS.md.
// Needs curl, unzip and ffmpeg/ffprobe on the PATH.
//
// Usage: node tools/audio/fetch-music.mjs <config.json>
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const cfgPath = process.argv[2];
if (!cfgPath) { console.error('usage: node tools/audio/fetch-music.mjs <config.json>'); process.exit(1); }
const cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
const cache = path.join(path.dirname(cfgPath), '.cache', 'music');
const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

// --- sources ----------------------------------------------------------------------
function source(track) {
  const dir = path.join(cache, track.id);
  const name = decodeURIComponent(new URL(track.url).pathname.split('/').pop());
  const download = path.join(dir, name);
  if (!fs.existsSync(download)) {
    fs.mkdirSync(dir, { recursive: true });
    console.log(`downloading ${track.title}…`);
    run('curl', ['-sSfL', '-o', download, track.url]);
    if (name.endsWith('.zip')) run('unzip', ['-q', '-o', download, '-d', path.join(dir, 'unzipped')]);
  }
  return track.file ? path.join(dir, 'unzipped', track.file) : download;
}

const duration = (file) => Number(run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).trim());

// --- tracks -----------------------------------------------------------------------
fs.mkdirSync(cfg.out, { recursive: true });
for (const f of fs.readdirSync(cfg.out)) if (f.endsWith(`.${cfg.encode.ext}`)) fs.rmSync(path.join(cfg.out, f));
const { lufs, truePeak, lra } = cfg.loudness;
const playlist = [];

for (const track of cfg.tracks) {
  const src = source(track);
  const repeat = track.repeat ?? 1;
  const total = duration(src) * repeat;
  const fade = `afade=t=out:st=${(total - cfg.fadeOut).toFixed(3)}:d=${cfg.fadeOut}`;
  const input = ['-stream_loop', String(repeat - 1), '-i', src];

  // pass 1: measure (loudnorm prints its JSON on stderr)
  const measure = spawnSync('ffmpeg', ['-hide_banner', '-nostats', ...input, '-af', `${fade},loudnorm=I=${lufs}:TP=${truePeak}:LRA=${lra}:print_format=json`, '-f', 'null', '-'], { encoding: 'utf8' }).stderr;
  const m = JSON.parse(measure.slice(measure.lastIndexOf('{'), measure.lastIndexOf('}') + 1));
  // pass 2: apply (linear when the headroom allows, so the dynamics are untouched)
  const norm = `loudnorm=I=${lufs}:TP=${truePeak}:LRA=${lra}:measured_I=${m.input_i}:measured_TP=${m.input_tp}:measured_LRA=${m.input_lra}:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true`;
  const file = `${track.id}.${cfg.encode.ext}`, out = path.join(cfg.out, file);
  run('ffmpeg', ['-v', 'error', '-y', ...input, '-af', `${fade},${norm}`, '-map_metadata', '-1', '-ar', String(cfg.encode.sampleRate), '-ac', '2', '-c:a', cfg.encode.codec, '-b:a', cfg.encode.bitrate, out]);

  const seconds = Math.round(duration(out));
  playlist.push({ file, title: track.title, author: track.author, seconds });
  console.log(`${file}  ${seconds}s  ${(fs.statSync(out).size / 1048576).toFixed(2)} MB  (source ${m.input_i} LUFS)`);
}
fs.writeFileSync(path.join(cfg.out, 'tracks.json'), JSON.stringify({ tracks: playlist }, null, 2) + '\n');

// --- credits ----------------------------------------------------------------------
const e = cfg.encode;
const lines = [
  '# Music credits', '',
  `Generated by tools/audio/fetch-music.mjs from ${path.relative(process.cwd(), cfgPath)}; edit the config, not this file.`, '',
  `Changes made to every track: repeated as listed (most sources are seamless loops), faded out over the last ${cfg.fadeOut} s, ` +
  `loudness-normalised to ${lufs} LUFS integrated (true peak ${truePeak} dBTP, two-pass EBU R128 loudnorm), ` +
  `re-encoded as ${e.ext.toUpperCase()} ${e.bitrate}bps ${e.sampleRate / 1000} kHz stereo, metadata stripped.`, '',
];
for (const t of cfg.tracks) {
  lines.push(`## ${t.title}`, '', `- Author: ${t.author}`, `- Source: ${t.page}`, `- License: ${t.license}`,
    `- File: ${t.id}.${e.ext}${t.file ? ` (from ${t.file} in the download)` : ''}, source repeated ${t.repeat ?? 1}×`, '');
}
fs.writeFileSync(path.join(cfg.out, 'CREDITS.md'), lines.join('\n'));
